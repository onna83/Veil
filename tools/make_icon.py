CURVE_SHADE = ("M47.5,61.8 C53,62.2 56,48.5 65.5,48 C73.5,47.6 77.5,55 81,58.6 C84,61.6 87,63.4 87,67.6 "
               "C87,70.6 85.6,72 83.5,72 L50,72 C58,70 66,62 47.5,61.8 Z")
