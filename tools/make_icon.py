LEAF_L = "M54,42 C50.5,33 41,30.2 35.5,33 C39,38.6 46.5,42.2 54,42 Z"
LEAF_R = "M54.2,41.5 C57,31.5 66,27.8 72.5,30.6 C69,37.2 61.5,41.5 54.2,41.5 Z"
